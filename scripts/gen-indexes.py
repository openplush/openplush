#!/usr/bin/env python3
"""Generate each docs folder's index list and the ADR table.

Parallel docs pull requests conflict on hand-kept index lists, so the docs step runs
this before building the book. Its includes are never committed:
  - docs/<folder>/index.inc for explanation, how-to, reference and tutorials: one
    entry per page docs/SUMMARY.md lists in that folder, in SUMMARY.md's order,
    "- [<the page's H1>](<file>): <its index line>". The folder's README.md includes it.
  - docs/adr/index.inc: one table row per docs/adr/NNNN-*.md but the template, in
    number order, "| [NNNN](<file>) | <its H1> | <its front matter's status> |".
    Rows only, so docs/adr/README.md keeps the table's header and the include
    carries no comment, which would end the table.
A page's H1 is its first non-blank line after any front matter; its index line,
"<!-- index: <one line> -->", is the first non-blank line after the H1.
It fails, writing nothing, naming the file, on: a listed page with no H1 or no
index line, an ADR with no H1 or no status in its front matter, a folder SUMMARY.md
lists no page of, and a missing SUMMARY.md or listed page.

Usage: scripts/gen-indexes.py [root]   (default root: the repository)
Tests: scripts/tests/gen-indexes.test.sh
"""

import re
import sys
from pathlib import Path

FOLDERS = ("explanation", "how-to", "reference", "tutorials")
INCLUDE = "index.inc"
SUMMARY = "docs/SUMMARY.md"
ADR_DIR = "docs/adr"
ADR_FILE = re.compile(r"(?P<number>[0-9]{4})-.+\.md")
ADR_TEMPLATE = "0000-template.md"
SUMMARY_LINK = re.compile(r"\s*[-*+]\s+\[[^\]]*\]\((?P<path>[^)]+)\)")
H1 = re.compile(r"# (?P<title>\S.*?)\s*")
INDEX_LINE = re.compile(r"<!-- index: (?P<text>\S.*?) -->\s*")
STATUS = re.compile(r"status:\s*(?P<status>\S.*?)\s*")
FOLDER_HEADER = (
    "<!-- Generated by scripts/gen-indexes.py from docs/SUMMARY.md and each page's"
    " index line; do not edit. -->\n\n"
)


class IndexSourceError(Exception):
    """A page or ADR an index entry cannot be read from without guessing."""


class Page:
    """A page's front matter lines and the lines after it; `name` is its path for messages."""

    def __init__(self, path: Path, name: str):
        self.name = name
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except OSError as e:
            raise IndexSourceError(f"{name}: cannot read: {e.strerror}") from e
        self.front: list[str] = []
        if lines and lines[0] == "---":
            if "---" not in lines[1:]:
                raise IndexSourceError(f"{name}: front matter has no closing '---'")
            end = lines.index("---", 1)
            self.front, lines = lines[1:end], lines[end + 1 :]
        self.body = [line for line in lines if line.strip()]

    def title(self) -> str:
        h1 = H1.fullmatch(self.body[0]) if self.body else None
        if h1 is None:
            raise IndexSourceError(f"{self.name}: no H1 ('# <title>') as its first line")
        return h1["title"]

    def index_line(self) -> str:
        self.title()
        line = INDEX_LINE.fullmatch(self.body[1]) if len(self.body) > 1 else None
        if line is None:
            raise IndexSourceError(f"{self.name}: no index line ('<!-- index: <one line> -->') just after its H1")
        return line["text"]

    def status(self) -> str:
        for line in self.front:
            if status := STATUS.fullmatch(line):
                return status["status"]
        raise IndexSourceError(f"{self.name}: no status in its front matter")


def listed(root: Path, folder: str) -> list[str]:
    """The pages SUMMARY.md lists in `folder`, in its order, relative to the folder."""
    try:
        lines = (root / SUMMARY).read_text(encoding="utf-8").splitlines()
    except OSError as e:
        raise IndexSourceError(f"{SUMMARY}: cannot read: {e.strerror}") from e
    prefix = f"{folder}/"
    pages = []
    for line in lines:
        link = SUMMARY_LINK.match(line)
        if link and link["path"].startswith(prefix) and link["path"] != f"{prefix}README.md":
            pages.append(link["path"][len(prefix) :])
    if not pages:
        raise IndexSourceError(f"docs/{prefix}: {SUMMARY} lists no page in it")
    return pages


def folder_list(root: Path, folder: str) -> str:
    entries = []
    for page in listed(root, folder):
        name = f"docs/{folder}/{page}"
        read = Page(root / name, name)
        entries.append(f"- [{read.title()}]({page}): {read.index_line()}\n")
    return FOLDER_HEADER + "".join(entries)


def adr_rows(root: Path) -> str:
    files = sorted(
        p.name for p in (root / ADR_DIR).glob("*.md") if ADR_FILE.fullmatch(p.name) and p.name != ADR_TEMPLATE
    )
    if not files:
        raise IndexSourceError(f"{ADR_DIR}/: no ADR (NNNN-*.md)")
    rows = []
    for file in files:
        name = f"{ADR_DIR}/{file}"
        read = Page(root / name, name)
        number = ADR_FILE.fullmatch(file)["number"]
        rows.append(f"| [{number}]({file}) | {read.title()} | {read.status()} |\n")
    return "".join(rows)


def render(root: Path) -> dict[str, str]:
    """Every include's path and text; reading every page before writing any include."""
    out = {f"docs/{folder}/{INCLUDE}": folder_list(root, folder) for folder in FOLDERS}
    out[f"{ADR_DIR}/{INCLUDE}"] = adr_rows(root)
    return out


def main(argv: list[str]) -> int:
    usage = "usage: scripts/gen-indexes.py [root]"
    if len(argv) > 1 or any(arg.startswith("-") for arg in argv):
        print(f"gen-indexes: unexpected arguments {' '.join(argv)!r}; {usage}", file=sys.stderr)
        return 2
    root = Path(argv[0]) if argv else Path(__file__).resolve().parent.parent
    try:
        for path, text in render(root).items():
            with open(root / path, "w", encoding="utf-8", newline="\n") as out:
                out.write(text)
    except (IndexSourceError, OSError) as e:
        print(f"gen-indexes: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
