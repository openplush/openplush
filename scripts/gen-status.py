#!/usr/bin/env python3
"""Generate the status page's task counts from every specs/*/tasks.md.

Counts are copied facts that drift when kept by hand, so the docs step runs this
before building the book. It writes docs/start/status-counts.inc, which is never
committed and which docs/start/status.md includes: a Markdown table
with one row per feature, in directory order, giving its ticked tasks of all its tasks.
A feature whose tasks.md front matter says `kind: process` (repository tooling, which
no maker sees) goes in a second table after the product features.
A task line starts "- [ ] " or "- [x] " and then a task ID (a capital letter, three
digits and an optional lower-case letter). It fails, writing nothing, on:
  - a line that starts with a checkbox but is not a task line (indented, another
    bullet or mark, a stray space in the box, no ID), since leaving it out of the
    counts would be silent;
  - a tasks.md with no task lines, or no specs/*/tasks.md at all;
  - a `kind:` other than `product` (the default) or `process`.

Usage: scripts/gen-status.py [root]   (default root: the repository)
Tests: scripts/tests/gen-status.test.sh
"""

import re
import sys
from pathlib import Path

INCLUDE = "docs/start/status-counts.inc"
TASKS_URL = "https://github.com/openplush/openplush/blob/main/specs/{}/tasks.md"
CHECKBOX = re.compile(r"\s*[-*+]\s*\[[^\]]{0,3}\](?!\()")
TASK = re.compile(r"- \[(?P<mark>[ x])\] [A-Z][0-9]{3}[a-z]?\b")
KIND = re.compile(r"kind:\s*(?P<kind>\S+)\s*$")
KINDS = ("product", "process")
HEADER = (
    "<!-- Generated by scripts/gen-status.py from specs/*/tasks.md; do not edit. -->\n"
    "\n"
)
TABLE = "| Feature | Tasks ticked |\n|---|---|\n"
PROCESS = "\nRepository process, with no change a maker sees:\n\n"


class StatusError(Exception):
    """A tasks.md the counts cannot be read from without guessing."""


def count(path: Path, name: str) -> tuple[int, int]:
    """Ticked and total task lines in one tasks.md; `name` is its path for messages."""
    ticked = total = 0
    lines = path.read_text(encoding="utf-8").splitlines()
    for n, line in enumerate(lines, start=1):
        task = TASK.match(line)
        if task is None:
            if CHECKBOX.match(line):
                raise StatusError(f"{name}:{n}: a checkbox line that is not a task line: {line.strip()[:80]}")
            continue
        total += 1
        ticked += task["mark"] == "x"
    if total == 0:
        raise StatusError(f"{name}: no task lines")
    return ticked, total


def kind(path: Path, name: str) -> str:
    """The `kind:` in a tasks.md's front matter, `product` when it has none."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0] != "---":
        return "product"
    for line in lines[1:]:
        if line == "---":
            break
        found = KIND.match(line)
        if found:
            if found["kind"] not in KINDS:
                raise StatusError(f"{name}: unknown kind '{found['kind']}' (want product or process)")
            return found["kind"]
    return "product"


def render(root: Path) -> str:
    features = sorted(p.parent.name for p in (root / "specs").glob("*/tasks.md"))
    if not features:
        raise StatusError("no specs/*/tasks.md found")
    rows: dict[str, list[str]] = {k: [] for k in KINDS}
    for feature in features:
        path, name = root / "specs" / feature / "tasks.md", f"specs/{feature}/tasks.md"
        ticked, total = count(path, name)
        label = feature.replace("-", " ")
        rows[kind(path, name)].append(f"| [{label}]({TASKS_URL.format(feature)}) | {ticked} of {total} |\n")
    out = HEADER + TABLE + "".join(rows["product"])
    if rows["process"]:
        out += PROCESS + TABLE + "".join(rows["process"])
    return out


def main(argv: list[str]) -> int:
    root = Path(__file__).resolve().parent.parent
    for arg in argv:
        if arg.startswith("-"):
            print(f"gen-status: unknown option '{arg}'", file=sys.stderr)
            return 2
        else:
            root = Path(arg)
    try:
        fresh = render(root)
        with open(root / INCLUDE, "w", encoding="utf-8", newline="\n") as out:
            out.write(fresh)
    except (StatusError, OSError) as e:
        print(f"gen-status: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
