"""Run spike S7 over the fixture corpus and the synthetic corpus, and print Markdown results tables.

Usage: python3 run.py            (from this directory; numpy + scipy)
"""

import platform

import numpy
import scipy

import corpus
import meshes
from flatten import run_chart


def pct(x: float) -> str:
    return f"{100 * x:.2g}%" if x >= 1e-6 else "0"


def stop(stats) -> str:
    """How the solver stopped, and the final gradient inf-norm."""
    if stats.termination == "-":
        return "-"
    return f"{stats.termination} ({stats.grad_inf:.0e})"


def table(charts) -> None:
    rows = [run_chart(c) for c in charts]
    header = [
        "Chart", "Tris", "Min angle (°)", "ΣK (°)", "Natural gap", "Max angle fix (°)", "Simple", "Reflex",
        "Pinned: status", "Init flips", "SD mean", "Max stretch", "Min compress", "Pinned: stop",
        "Free: SD mean", "Free: max stretch", "Free: min compress",
        "Free: seam-length err (max edge / perimeter)", "Free: stop",
    ]
    print("| " + " | ".join(header) + " |")
    print("|" + "---|" * len(header))
    for r in rows:
        p, f = r.pinned, r.free
        print(
            f"| {r.name} | {r.triangles} | {r.min_angle_deg:.1f} | {r.total_gauss_deg + 0.0:.0f} | {pct(r.natural_gap)} | "
            f"{r.closure_max_change_deg:.2f} | {'yes' if r.boundary_simple else '**no**'} | {r.reflex_corners} | "
            f"{p.status if p.status == 'ok' else '**' + p.status + '**'} | {p.init}:{p.init_flips} | "
            f"{p.sd_mean:.3f} | {p.stretch_max:.3f} | {p.compress_min:.3f} | {stop(p)} | "
            f"{f.sd_mean:.3f} | {f.stretch_max:.3f} | {f.compress_min:.3f} | "
            f"{pct(f.boundary_len_err_max)} / {pct(f.perimeter_err)} | {stop(f)} |"
        )


def fixture_table(charts: list[corpus.FixtureChart]) -> None:
    """Fixture charts, pinned against free, with area-integrated measures."""
    header = [
        "Chart", "Tris", "Min angle (°)", "ΣK (°)", "Max cone (°)", "Natural gap", "Max angle fix (°)",
        "Simple", "Reflex", "Pinned: status", "Start", "Pinned: stop", "SD mean", "Max stretch",
        "Min compress", "Compress, 5% area", "Mean compress deficit", "Mean stretch excess",
        "Free: SD mean", "Free: min compress", "Free: seam-length err (max edge / perimeter)",
        "Free: outline simple", "Free: stop",
    ]
    print("| " + " | ".join(header) + " |")
    print("|" + "---|" * len(header))
    for c in charts:
        r = run_chart(c.chart)
        p, f = r.pinned, r.free
        print(
            f"| {r.name} | {r.triangles} | {r.min_angle_deg:.1f} | {r.total_gauss_deg + 0.0:.1f} | "
            f"{r.max_cone_deg + 0.0:.1f} | {r.natural_gap:.0e} | {r.closure_max_change_deg:.3f} | "
            f"{'yes' if r.boundary_simple else '**no**'} | {r.reflex_corners} | "
            f"{p.status if p.status == 'ok' else '**' + p.status + '**'} | {p.init}:{p.init_flips} | {stop(p)} | "
            f"{p.sd_mean:.3f} | {p.stretch_max:.3f} | {p.compress_min:.3f} | {p.compress_p5:.3f} | "
            f"{p.compress_deficit:.4f} | {p.stretch_excess:.4f} | "
            f"{f.sd_mean:.3f} | {f.compress_min:.3f} | {pct(f.boundary_len_err_max)} / {pct(f.perimeter_err)} | "
            f"{'yes' if f.outline_simple else '**no**'} | {stop(f)} |"
        )


def main() -> None:
    print(f"Generated by run.py with Python {platform.python_version()}, numpy {numpy.__version__}, "
          f"scipy {scipy.__version__}.\n")
    print("## Fixture corpus\n")
    print("Every chart of every `fixtures/seams/*.json` cut, as committed. Natural gap is a fraction of")
    print("the perimeter; the compress columns are smallest singular values (1 = none).\n")
    fixture_table([c for name in corpus.NAMES for c in corpus.load(name)])
    print("\n### Asymmetric variants\n")
    print("The same charts with every mesh vertex moved by a seeded random vector of length at most")
    print(f"{corpus.JITTER:g} x its shortest edge, before cutting. The committed charts are symmetric or")
    print("developable, so their outlines close by symmetry alone; these exercise closure.\n")
    fixture_table([c for name in corpus.NAMES for c in corpus.load(name, jitter=corpus.JITTER)])
    print("\n### Refinement sweep (fixture charts)\n")
    print("One and two levels of midpoint subdivision. Unjittered meshes are projected onto the")
    print("analytic sphere, capsule, or cube. Jittered meshes are jittered once, at the committed")
    print("resolution, then refined flat, so each level is the same polyhedron. One chart per shape.\n")
    distinct = {"sphere": (0,), "capsule": (0, 1), "cube": (0,)}
    fixture_table([corpus.load(name, levels, j)[k] for name, ks in distinct.items() for k in ks
                   for j in (0.0, corpus.JITTER) for levels in (0, 1, 2)])
    print("\n## Synthetic corpus\n")
    print("### Corpus\n")
    table(meshes.corpus())
    print("\n### Stress\n")
    table(meshes.stress())
    print("\n### Resolution sweep (stress caps)\n")
    print("Same shapes at four mesh resolutions. Closure and injectivity are stable; the extreme")
    print("singular values (max stretch, min compress) are not, so they are mesh-dependent at the")
    print("rim and should not be read as converged physical values.\n")
    shapes = (
        ("lobed-cap-p175", ((4, 0.16, 0.0), (1, 0.05, 0.3))),
        ("asym-cap-p175", ((1, 0.2, 0.0), (2, 0.1, 1.3), (5, 0.03, 0.0))),
        ("star-cap-p175", ((6, 0.12, 0.0), (1, 0.03, 0.0))),
    )
    sweep = [
        meshes.sphere_cap(175, rings=rings, peak=True, lobes=lobes, name=f"{name} r{rings}")
        for rings in (8, 16, 24, 32)
        for name, lobes in shapes
    ]
    table(sweep)


if __name__ == "__main__":
    main()
