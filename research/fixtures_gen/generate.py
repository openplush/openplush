"""Generate the fixture corpus: clean meshes, one model per defect class, reference seam sets, and source-seam models.

Run: python3 generate.py [output-root]   (default: the repository's fixtures/ directory)
Output is byte-for-byte reproducible; test_fixtures.py checks the committed files against it.
Units are millimetres.
"""

import json
import math
import sys
from dataclasses import dataclass, field
from pathlib import Path

Vec = tuple[float, float, float]
Face = tuple[int, int, int]
Edge = tuple[int, int]

FIXTURES = Path(__file__).resolve().parents[2] / "fixtures"
HEADER = "# OpenPlush fixture, CC0-1.0. Units: millimetres. Generated by research/fixtures_gen; do not edit.\n"
GRID = 3  # cube subdivisions per side: gives each face chart interior vertices, and defects room apart
STEP = 30.0  # mm between cube grid lines, so every cube coordinate and midpoint is exact in decimal
SEGMENTS = 12  # around the axis of revolution
PLUS_X, TOP = 0, 4  # indices into the per-side face lists cube() returns


@dataclass
class Mesh:
    pos: list[Vec] = field(default_factory=list)
    faces: list[Face] = field(default_factory=list)

    def add(self, p: Vec) -> int:
        self.pos.append(p)
        return len(self.pos) - 1


def revolve(profile: list[tuple[float, float]], top: float, bottom: float) -> tuple[Mesh, list[list[int]]]:
    """Surface of revolution about z: a pole, rings of (radius, z) from top to bottom, a pole."""
    m = Mesh()
    north = m.add((0.0, 0.0, top))
    turn = [2 * math.pi * j / SEGMENTS for j in range(SEGMENTS)]
    rings = [[m.add((r * math.cos(t), r * math.sin(t), z)) for t in turn] for r, z in profile]
    south = m.add((0.0, 0.0, bottom))
    for j in range(SEGMENTS):
        k = (j + 1) % SEGMENTS
        m.faces.append((north, rings[0][j], rings[0][k]))
        for up, down in zip(rings, rings[1:]):
            m.faces += [(up[j], down[j], down[k]), (up[j], down[k], up[k])]
        m.faces.append((south, rings[-1][k], rings[-1][j]))
    return m, rings


def sphere() -> tuple[Mesh, list[list[int]]]:
    r, n = 50.0, 8
    return revolve([(r * math.sin(math.pi * i / n), r * math.cos(math.pi * i / n)) for i in range(1, n)], r, -r)


def capsule() -> tuple[Mesh, list[list[int]]]:
    r, half = 30.0, 30.0
    cap = [(r * math.sin(math.pi * i / 6), half + r * math.cos(math.pi * i / 6)) for i in range(1, 4)]
    tube = [(r, 10.0), (r, -10.0)]
    return revolve(cap + tube + [(rr, -z) for rr, z in reversed(cap)], half + r, -half - r)


def cube() -> tuple[Mesh, list[list[Face]], dict[tuple[int, int, int], int]]:
    """Axis-aligned cube of side GRID * STEP centred on the origin; returns faces per side and grid keys."""
    m = Mesh()
    keys: dict[tuple[int, int, int], int] = {}
    sides: list[list[Face]] = []
    for axis in range(3):
        for hi in (True, False):
            u, v = ((axis + 1) % 3, (axis + 2) % 3) if hi else ((axis + 2) % 3, (axis + 1) % 3)
            side: list[Face] = []

            def at(i: int, j: int) -> int:
                key = [GRID if hi else 0] * 3
                key[u], key[v] = i, j
                k = (key[0], key[1], key[2])
                if k not in keys:
                    keys[k] = m.add((STEP * (k[0] - GRID / 2), STEP * (k[1] - GRID / 2), STEP * (k[2] - GRID / 2)))
                return keys[k]

            for i in range(GRID):
                for j in range(GRID):
                    a, b, c, d = at(i, j), at(i + 1, j), at(i + 1, j + 1), at(i, j + 1)
                    side += [(a, b, c), (a, c, d)]
            m.faces += side
            sides.append(side)
    return m, sides, keys


def tetra(m: Mesh, pts: list[Vec | int]) -> None:
    """Closed tetrahedron, wound outward; an int in `pts` reuses that existing vertex."""
    ids = [p if isinstance(p, int) else m.add(p) for p in pts]
    a, b, c, d = (m.pos[i] for i in ids)
    e1, e2, e3 = ([q[k] - a[k] for k in range(3)] for q in (b, c, d))
    det = (
        e1[0] * (e2[1] * e3[2] - e2[2] * e3[1])
        - e1[1] * (e2[0] * e3[2] - e2[2] * e3[0])
        + e1[2] * (e2[0] * e3[1] - e2[1] * e3[0])
    )
    if det < 0:
        ids[1], ids[2] = ids[2], ids[1]
    i0, i1, i2, i3 = ids
    m.faces += [(i0, i2, i1), (i0, i1, i3), (i0, i3, i2), (i1, i2, i3)]


def defects() -> dict[str, tuple[str, Mesh]]:
    """Each model is the cube with one defect added; the string says what and where."""
    out: dict[str, tuple[str, Mesh]] = {}
    m, _, key = cube()
    a, b = key[(1, 0, GRID)], key[(2, 0, GRID)]
    tetra(m, [a, b, (0.0, -51.0, 63.0), (0.0, -63.0, 51.0)])
    out["non-manifold-edge"] = ("a closed fin shares one cube edge, so that edge has four faces", m)

    m, _, key = cube()
    tetra(m, [key[(GRID, GRID, GRID)], (57.0, 57.0, 48.0), (48.0, 57.0, 57.0), (57.0, 48.0, 57.0)])
    out["bowtie-vertex"] = ("a closed tetrahedron touches one cube corner, so that vertex has two fans", m)

    m, sides, _ = cube()
    flipped = set(sides[PLUS_X])
    m.faces = [(f[0], f[2], f[1]) if f in flipped else f for f in m.faces]
    out["flipped-normals"] = ("the +x side is wound inward", m)

    m, _, key = cube()
    a, b = key[(1, 1, GRID)], key[(2, 1, GRID)]
    i = next(i for i, f in enumerate(m.faces) if (a, b) in ((f[0], f[1]), (f[1], f[2]), (f[2], f[0])))
    c = next(v for v in m.faces[i] if v not in (a, b))
    (ax, ay, az), (bx, by, bz) = m.pos[a], m.pos[b]
    mid = m.add(((ax + bx) / 2, (ay + by) / 2, (az + bz) / 2))
    m.faces[i : i + 1] = [(a, mid, c), (mid, b, c), (a, b, mid)]
    out["zero-area-face"] = ("one top face is split by a collinear sliver; the mesh stays closed", m)

    m, _, _ = cube()
    m.faces.append(m.faces[0])
    out["duplicate-face"] = ("the first face is repeated with the same winding", m)

    m, sides, _ = cube()
    quad = 2 * (GRID * (GRID // 2) + GRID // 2)  # first triangle of the centre quad
    middle = sides[TOP][quad : quad + 2]
    m.faces = [f for f in m.faces if f not in middle]
    out["hole"] = ("the middle quad of the top side is missing", m)

    m, sides, _ = cube()
    top = set(sides[TOP])
    shared = sorted({v for f in top for v in f} & {v for f in m.faces if f not in top for v in f})
    copy = {v: m.add(m.pos[v]) for v in shared}
    m.faces = [(copy.get(f[0], f[0]), copy.get(f[1], f[1]), copy.get(f[2], f[2])) if f in top else f for f in m.faces]
    out["unwelded-split-vertices"] = ("the top side has its own copies of its border vertices, as a glTF UV split", m)

    m, _, key = cube()
    v = key[(1, 1, GRID)]
    m.pos[v] = (-9.0, -21.0, -60.0)  # off the grid lines, so the crossings are transverse, not edge-on
    out["self-intersection"] = ("one top vertex is pushed through the bottom side", m)

    m, _, _ = cube()
    tetra(m, [(100.0, 0.0, 0.0), (120.0, 0.0, 0.0), (100.0, 20.0, 0.0), (100.0, 0.0, 20.0)])
    out["multi-component"] = ("a separate closed tetrahedron floats beside the cube", m)
    return out


def seams() -> dict[str, tuple[str, list[Edge]]]:
    """Reference cuts that leave every chart a disk."""
    def path(vs: list[int]) -> list[Edge]:
        return list(zip(vs, vs[1:]))

    _, sphere_rings = sphere()
    north, south = 0, sum(len(r) for r in sphere_rings) + 1
    gores = [e for j in range(0, SEGMENTS, 2) for e in path([north] + [r[j] for r in sphere_rings] + [south])]

    _, cap_rings = capsule()
    rims = [cap_rings[2], cap_rings[5]]
    tube = [e for rim in rims for e in path(rim + rim[:1])] + path([r[0] for r in cap_rings[2:6]])

    _, _, key = cube()
    g, line = GRID, range(GRID + 1)
    tree = [[(0, g, k) for k in line]]
    for z in (0, g):
        tree += [[(0, j, z) for j in line], [(i, g, z) for i in line], [(g, j, z) for j in line]]
    net = [e for run in tree for e in path([key[k] for k in run])]
    return {
        "sphere": ("six gores, cut pole to pole along every other meridian", gores),
        "capsule": ("two end caps and a tube slit lengthwise", tube),
        "cube": ("a cross-shaped cube net: three top, three bottom, and one vertical cube edge", net),
    }


def num(x: float) -> str:
    return f"{round(x, 6) + 0.0:.6f}"  # + 0.0 turns -0.0 into 0.0


def obj_text(note: str, m: Mesh) -> str:
    lines = [HEADER, f"# {note}\n"]
    lines += [f"v {num(p[0])} {num(p[1])} {num(p[2])}\n" for p in m.pos]
    lines += [f"f {f[0] + 1} {f[1] + 1} {f[2] + 1}\n" for f in m.faces]
    return "".join(lines)


def seam_text(mesh: str, note: str, edges: list[Edge], kind: str = "cut") -> str:
    """`mesh` is the OBJ the edge indices refer to, relative to fixtures/; every seam gets `kind`."""
    entries = sorted({(min(e), max(e)) for e in edges})
    head = {"format": "openplush-seam-set", "version": 1, "mesh": mesh, "vertexIndexBase": 0, "note": note}
    body = ",\n".join(f'    {{"edge": [{a}, {b}], "kind": "{kind}"}}' for a, b in entries)
    return json.dumps(head, indent=2)[:-2] + ',\n  "seams": [\n' + body + "\n  ]\n}\n"


def write_all(root: Path) -> None:
    bases = {"capsule": capsule()[0], "cube": cube()[0], "sphere": sphere()[0]}
    files = {f"meshes/{n}.obj": obj_text(f"{n}: closed, manifold, outward", m) for n, m in bases.items()}
    files |= {f"defects/{n}.obj": obj_text(note, m) for n, (note, m) in defects().items()}
    files |= {f"seams/{n}.json": seam_text(f"meshes/{n}.obj", note, e) for n, (note, e) in seams().items()}
    data = {rel: text.encode("utf-8") for rel, text in files.items()}
    from source_dead_end import dead_end_files  # imported here: these modules build on this one's shapes
    from source_seams import source_seam_files

    data |= source_seam_files() | dead_end_files()
    for rel, blob in sorted(data.items()):
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_bytes(blob)


if __name__ == "__main__":
    write_all(Path(sys.argv[1]) if len(sys.argv) > 1 else FIXTURES)
